// Packaged WebView2 checks. This script uses real native IPC and saved pins.
import { createRequire } from 'node:module';
import path from 'node:path';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require(path.join(process.env.BLOOM_TEST_TOOLS,'playwright'));
const out=process.env.BLOOM_EVIDENCE;
await fs.mkdir(out,{recursive:true});
const browser=await chromium.connectOverCDP('http://127.0.0.1:49333');
const pages=browser.contexts().flatMap(c=>c.pages());
const main=pages.find(p=>p.url()==='http://tauri.localhost/');
const dock=pages.find(p=>p.url().endsWith('/dock.html'));
const overlay=pages.find(p=>p.url().endsWith('/overlay.html'));
assert(main&&dock&&overlay);
const invoke=(cmd,args={})=>dock.evaluate(({cmd,args})=>window.__TAURI_INTERNALS__.invoke(cmd,args),{cmd,args});
await main.getByRole('region',{name:'Bloom top notch'}).waitFor({state:'visible'});
await dock.locator('.dock-expanded').waitFor();
await main.mouse.move(20,300);
await main.waitForTimeout(3500);
const settings=await invoke('load_settings');
assert.equal(settings['bloom-notch-mode'],'overlay');
assert.equal(await main.locator('.mac-menu-bar').count(),0);
assert.equal(await overlay.locator('.volume-notch-wrapper,.brightness-notch-wrapper').count(),0);
const notch=main.getByRole('region',{name:'Bloom top notch'});
const resting=await notch.boundingBox();
assert(resting.y>=-1&&resting.y<1,JSON.stringify(resting));
assert(resting.height>=35);
await main.screenshot({path:path.join(out,'native-notch-resting.png'),omitBackground:true});
await notch.click({button:'right'});
await main.getByLabel('Master volume',{exact:true}).waitFor({state:'visible'});
await main.getByLabel('Display brightness',{exact:true}).waitFor({state:'visible'});
await main.waitForTimeout(500);
await main.screenshot({path:path.join(out,'native-notch-controls.png'),omitBackground:true});
await main.getByRole('button',{name:'App volumes',exact:true}).click();
await main.waitForTimeout(700);
const sessions=await invoke('get_audio_sessions');
assert(Array.isArray(sessions));
await main.screenshot({path:path.join(out,'native-notch-mixer.png'),omitBackground:true});
await main.mouse.move(20,300);
await main.waitForTimeout(1600);
const pins=await invoke('load_pinned_apps');
const rendered=await dock.locator('.dock-reorder-group > div').count();
assert.equal(rendered,pins.length);
const imageRatio=await dock.locator('.dock-icon img').first().evaluate(img=>img.getBoundingClientRect().width/img.parentElement.getBoundingClientRect().width);
assert(imageRatio<.9);
await dock.screenshot({path:path.join(out,'native-dock-window.png'),omitBackground:true});
await dock.locator('.dock').screenshot({path:path.join(out,'native-dock-small-logos.png'),omitBackground:true});
// Intercept verification clicks before React, so no user app is launched.
await dock.evaluate(()=>{
 window.__nativeDockProbe=[];
 document.addEventListener('click',event=>{
  const icon=event.target.closest?.('.dock-icon-wrapper');
  if(!icon)return;
  const index=[...document.querySelectorAll('.dock-icon-wrapper')].indexOf(icon);
  window.__nativeDockProbe.push({index,x:event.clientX,y:event.clientY});
  event.preventDefault();event.stopImmediatePropagation();
 },true);
});
const targets=await dock.locator('.dock-icon-wrapper').evaluateAll(els=>els.map((el,index)=>{const r=el.getBoundingClientRect();return{index,name:el.querySelector('.tooltip')?.textContent,x:r.x+r.width/2,y:r.y+r.height/2};}));
const report={passed:true,source:'packaged Windows WebView2, real IPC; renderer interactions',resting,pins:pins.length,rendered,imageRatio,audioSessions:sessions.length,topBarRemoved:true,sidePanelsRemoved:true,overlayMode:settings['bloom-notch-mode'],targets};
await fs.writeFile(path.join(out,'native-notch-verification.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify({passed:true,resting,pins:pins.length,audioSessions:sessions.length,imageRatio,mouseTargets:targets.filter(t=>[0,Math.floor(targets.length/2),targets.length-2,targets.length-1].includes(t.index))},null,2));
await browser.close();
